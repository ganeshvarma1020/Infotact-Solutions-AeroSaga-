-- Never edit a migration that has already run; add V2__..., V3__... instead.

create table mission (
    id              varchar(64)   primary key,
    operator        varchar(100)  not null,
    payload_kg      double precision not null,
    waypoint_count  integer       not null,
    route_km        double precision not null,
    scenario        varchar(32)   not null,
    phase           varchar(32)   not null,
    drone_id        varchar(32),
    failure_code    varchar(64),
    failure_reason  varchar(1000),
    created_at      timestamp with time zone not null,
    updated_at      timestamp with time zone not null,
    finished_at     timestamp with time zone
);

create index idx_mission_created on mission (created_at);

create table mission_event (
    id           bigint generated by default as identity primary key,
    mission_id   varchar(64)   not null references mission (id),
    phase        varchar(32)   not null,
    message      varchar(1000) not null,
    occurred_at  timestamp with time zone not null
);

create index idx_mission_event_mission on mission_event (mission_id, occurred_at);
